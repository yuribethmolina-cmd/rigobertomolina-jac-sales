/** Busca por id, slug antiguo, nombre o alias (mantiene URLs existentes vivas). */
export const findVehicle = (key?: string): Vehicle | undefined => {
  if (!key) return undefined;
  const k = slugify(key);
  return vehicles.find(
    (v) =>
      v.id === k ||
      slugify(v.canonicalName) === k ||
      v.aliases.some((a) => slugify(a) === k)
  );
};

export const vehicleCategoryOf = (key: string) => findVehicle(key)?.category;
